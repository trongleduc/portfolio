/**
 * Resets the Supabase portfolio tables and seeds them from the static data in src/data.
 *
 *   npm run db:sql                                  -> writes supabase/seed.sql for the SQL Editor
 *   npx tsx --env-file=.env.local scripts/seed.ts   -> read-only: prints current row counts
 *   npm run db:reset                                -> DESTRUCTIVE: drop, recreate, seed
 *
 * The reset drops the 9 portfolio tables in the public schema, recreates them from
 * supabase/schema.sql (including RLS policies) and inserts the sample data, all in one
 * transaction, so a failure leaves the database unchanged. Storage buckets, Auth users and
 * any other tables are not touched.
 *
 * Requires SUPABASE_DB_URL in .env.local: the Postgres connection string from the Supabase
 * dashboard (Connect -> Session pooler).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Client } from "pg";
import {
  profileData,
  projectsData,
  workHistoryData,
  educationData,
  techStackData,
} from "../src/data";

const TABLES = [
  "profiles",
  "projects",
  "work_history",
  "education",
  "languages",
  "frontend",
  "backend",
  "workflow_ai",
  "coding_tools",
] as const;

type Table = (typeof TABLES)[number];
type Row = Record<string, unknown>;

const DATE_COLUMNS = new Set(["start_date", "end_date"]);
const JSON_COLUMNS = new Set(["images"]);

const seedRows: Record<Table, Row[]> = {
  profiles: [profileData as unknown as Row],
  projects: projectsData.map((p, i) => ({ ...p, display_order: i })),
  work_history: workHistoryData as unknown as Row[],
  education: educationData as unknown as Row[],
  languages: techStackData.languages as unknown as Row[],
  frontend: techStackData.frontend as unknown as Row[],
  backend: techStackData.backend as unknown as Row[],
  workflow_ai: techStackData.workflowAi as unknown as Row[],
  coding_tools: techStackData.codingTools as unknown as Row[],
};

/** Normalizes a value for Postgres: "" dates become NULL, JSON columns are serialized. */
function toDbValue(column: string, value: unknown): unknown {
  if (DATE_COLUMNS.has(column) && value === "") return null;
  if (JSON_COLUMNS.has(column)) return JSON.stringify(value ?? []);
  return value;
}

/** Renders a value as a SQL literal for the generated seed.sql. */
function sqlLiteral(column: string, value: unknown): string {
  const v = toDbValue(column, value);
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "number") return String(v);
  const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
  if (Array.isArray(v)) {
    return v.length ? `ARRAY[${v.map((x) => quote(String(x))).join(", ")}]::text[]` : "'{}'::text[]";
  }
  if (JSON_COLUMNS.has(column)) return `${quote(String(v))}::jsonb`;
  return quote(String(v));
}

function writeSeedSql() {
  const schema = readFileSync(join(process.cwd(), "supabase", "schema.sql"), "utf8");
  const inserts = TABLES.flatMap((table) =>
    seedRows[table].map((row) => {
      const columns = Object.keys(row).filter((c) => row[c] !== undefined);
      return `INSERT INTO public.${table} (${columns.map((c) => `"${c}"`).join(", ")}) VALUES (${columns
        .map((c) => sqlLiteral(c, row[c]))
        .join(", ")});`;
    }),
  );
  const counts = TABLES.map(
    (t) => `SELECT '${t}' AS table_name, COUNT(*) AS rows, ${seedRows[t].length} AS expected FROM public.${t}`,
  ).join("\nUNION ALL ");

  const out = [
    "-- GENERATED by `npm run db:sql` from src/data + supabase/schema.sql. Do not edit by hand.",
    "-- DESTRUCTIVE: drops and recreates the 9 portfolio tables in the public schema, then seeds them.",
    "-- Storage buckets and Auth users are not touched. Paste into Supabase Dashboard -> SQL Editor -> Run.",
    "",
    "BEGIN;",
    "",
    `DROP TABLE IF EXISTS ${TABLES.map((t) => `public.${t}`).join(", ")} CASCADE;`,
    "",
    schema.trim(),
    "",
    ...inserts,
    "",
    "COMMIT;",
    "",
    "-- Verification: every row should have rows = expected.",
    `${counts};`,
    "",
  ].join("\n");

  const target = join(process.cwd(), "supabase", "seed.sql");
  writeFileSync(target, out, "utf8");
  console.log(`Wrote ${target} (${inserts.length} inserts).`);
}

async function insertRow(db: Client, table: Table, row: Row) {
  const columns = Object.keys(row).filter((c) => row[c] !== undefined);
  const placeholders = columns.map((_, i) => `$${i + 1}`);
  const values = columns.map((c) => toDbValue(c, row[c]));
  await db.query(
    `INSERT INTO public.${table} (${columns.map((c) => `"${c}"`).join(", ")}) VALUES (${placeholders.join(", ")})`,
    values,
  );
}

async function countRows(db: Client): Promise<Map<Table, number | null>> {
  const counts = new Map<Table, number | null>();
  for (const table of TABLES) {
    const { rows } = await db.query<{ exists: boolean }>(
      "SELECT to_regclass($1) IS NOT NULL AS exists",
      [`public.${table}`],
    );
    if (!rows[0].exists) {
      counts.set(table, null);
      continue;
    }
    const res = await db.query<{ n: number }>(`SELECT COUNT(*)::int AS n FROM public.${table}`);
    counts.set(table, res.rows[0].n);
  }
  return counts;
}

async function main() {
  if (process.argv.includes("--sql")) {
    writeSeedSql();
    return;
  }

  const url = process.env.SUPABASE_DB_URL;
  if (!url) {
    console.error("SUPABASE_DB_URL is not set (expected in .env.local).");
    process.exit(1);
  }

  const db = new Client({ connectionString: url, ssl: { rejectUnauthorized: false } });
  await db.connect();

  try {
    if (!process.argv.includes("--yes")) {
      console.log("Read-only mode. Current row counts (re-run with --yes to reset):");
      for (const [table, n] of await countRows(db)) {
        console.log(`  ${table.padEnd(13)} ${n === null ? "(missing)" : n}`);
      }
      return;
    }

    const schema = readFileSync(join(process.cwd(), "supabase", "schema.sql"), "utf8");
    console.log(`Resetting ${TABLES.length} tables in Supabase...`);

    await db.query("BEGIN");
    try {
      await db.query(`DROP TABLE IF EXISTS ${TABLES.map((t) => `public.${t}`).join(", ")} CASCADE`);
      await db.query(schema);
      for (const table of TABLES) {
        for (const row of seedRows[table]) await insertRow(db, table, row);
      }
      await db.query("COMMIT");
    } catch (err) {
      await db.query("ROLLBACK");
      throw err;
    }

    let mismatch = false;
    for (const [table, n] of await countRows(db)) {
      const expected = seedRows[table].length;
      const ok = n === expected;
      if (!ok) mismatch = true;
      console.log(`${ok ? "OK  " : "FAIL"} ${table.padEnd(13)} ${n}/${expected}`);
    }
    if (mismatch) {
      console.error("Row counts do not match the seed data.");
      process.exitCode = 1;
      return;
    }
    console.log("Supabase reset and seeded.");
  } finally {
    await db.end();
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
